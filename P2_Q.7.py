km = float(input("Enter kilometers:"))
celsius = float(input("Enter temperature in celsius:"))
rupees = float(input("Enter Rupees:"))

meters = km * 1000
fahrenheit = (celsius * 9/5) + 32
dollars = rupees /85

print("Meters =", meters)
print("Fahrenheit =", fahrenheit)
print("US Dollars=", round(dollars, 2))

    
               

                
